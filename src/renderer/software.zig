fn glyph8(cp: u21) [8]u8 {
    if (cp >= 32 and cp <= 126) return FONT8[cp - 32];
    return .{ 0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00 };
}

/// CPU rasterizer: terminal cells → packed 0xAARRGGBB framebuffer.
pub const SoftwareRenderer = struct {
    allocator: std.mem.Allocator,
    pixels: []u32,
    width: u32,
    height: u32,
    dirty: bool,

    pub fn init(allocator: std.mem.Allocator, cols: u16, rows: u16) !SoftwareRenderer {
        const width = @as(u32, cols) * CELL_W;
        const height = @as(u32, rows) * CELL_H;
        const pixels = try allocator.alloc(u32, width * height);
        @memset(pixels, 0xFF000000);
        return .{
            .allocator = allocator,
            .pixels = pixels,
            .width = width,
            .height = height,
            .dirty = true,
        };
    }

    pub fn deinit(self: *SoftwareRenderer) void {
        self.allocator.free(self.pixels);
        self.pixels = &.{};
    }

    pub fn renderGrid(
        self: *SoftwareRenderer,
        cells: []const Cell,
        rows: u16,
        cols: u16,
        cursor_row: u16,
        cursor_col: u16,
        cursor_visible: bool,
    ) void {
        @memset(self.pixels, 0xFF000000);
        var row: u16 = 0;
        while (row < rows) : (row += 1) {
            var col: u16 = 0;
            while (col < cols) : (col += 1) {
                const idx = @as(usize, row) * @as(usize, cols) + col;
                if (idx >= cells.len) break;
                blit(self, col, row, cells[idx], cursor_visible and row == cursor_row and col == cursor_col);
            }
        }
        self.dirty = true;
    }
};

fn blit(self: *SoftwareRenderer, col: u16, row: u16, cell: Cell, invert: bool) void {
    const ox = @as(u32, col) * CELL_W;
    const oy = @as(u32, row) * CELL_H;
    var fg = (cell.fg_color & 0x00FFFFFF) | 0xFF000000;
    var bg = (cell.bg_color & 0x00FFFFFF) | 0xFF000000;
    if (invert) {
        const tmp = fg;
        fg = bg;
        bg = tmp;
    }
    const bits = glyph8(cell.char);
    var gy: u32 = 0;
    while (gy < CELL_H) : (gy += 1) {
        const row_bits = bits[gy / 2];
        var gx: u32 = 0;
        while (gx < CELL_W) : (gx += 1) {
            const on = (row_bits & (@as(u8, 1) << @intCast(gx))) != 0;
            const px = ox + gx;
            const py = oy + gy;
            if (px >= self.width or py >= self.height) continue;
            self.pixels[py * self.width + px] = if (on) fg else bg;
        }
    }
}

test "software renderer allocates framebuffer" {
    var r = try SoftwareRenderer.init(std.testing.allocator, 4, 2);
    defer r.deinit();
    try std.testing.expectEqual(@as(u32, 32), r.width);
    try std.testing.expectEqual(@as(u32, 32), r.height);
}

test "software renderer draws ASCII glyph" {
    var r = try SoftwareRenderer.init(std.testing.allocator, 2, 1);
    defer r.deinit();
    var cells = [_]Cell{ Cell.init(), Cell.init() };
    cells[0].char = 'A';
    cells[0].fg_color = 0xFFFFFF;
    cells[0].bg_color = 0x000000;
    r.renderGrid(&cells, 1, 2, 0, 1, true);

    var lit: usize = 0;
    for (r.pixels[0 .. CELL_W * CELL_H]) |px| {
        if (px == 0xFFFFFFFF) lit += 1;
    }
    try std.testing.expect(lit > 8);
}
