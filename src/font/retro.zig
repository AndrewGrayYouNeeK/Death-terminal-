/// Box with a dot, drawn for codepoints the 8x8 font lacks.
pub const replacement_bits: [8]u8 = .{ 0x7E, 0x42, 0x5A, 0x52, 0x4A, 0x42, 0x7E, 0x00 };

pub fn has(cp: u21) bool {
    return cp >= 32 and cp <= 126;
}

pub fn bits(cp: u21) [8]u8 {
    if (has(cp)) return FONT8[cp - 32];
    return replacement_bits;
}

/// Nearest-neighbour stretch of a glyph into a w*h coverage buffer.
pub fn render(cp: u21, w: u32, h: u32, out: []u8) void {
    const b = bits(cp);
    var y: u32 = 0;
    while (y < h) : (y += 1) {
        const row = b[y * glyph_px / h];
        var x: u32 = 0;
        while (x < w) : (x += 1) {
            const sx = x * glyph_px / w;
            out[y * w + x] = if ((row >> @intCast(sx)) & 1 != 0) 255 else 0;
        }
    }
}

test "retro glyph stretches to the cell" {
    var buf: [8 * 16]u8 = undefined;
    render('|', 8, 16, &buf);
    var lit: u32 = 0;
    for (buf) |p| lit += @intFromBool(p == 255);
    try std.testing.expect(lit >= 16);
    render(' ', 8, 16, &buf);
    for (buf) |p| try std.testing.expectEqual(@as(u8, 0), p);
}
