//! Automatic shell integration: start bash, zsh or fish so that they load
//! Death Terminal's OSC 133/OSC 7 snippets (shell-integration/*) on top of
//! the user's own startup files.
//!
//!   bash  --rcfile <dir>/bashrc, which sources ~/.bashrc and then the
//!         snippet (only when no shell.args are configured, so login shells
//!         and custom invocations are left alone)
//!   zsh   ZDOTDIR=<dir>/zsh; its .zshenv restores the user's ZDOTDIR,
//!         sources their .zshenv and then the snippet
//!   fish  --init-command "source <dir>/fish.fish"
//!
//! Other shells start unchanged. The files live in
//! $XDG_RUNTIME_DIR/deathterminal or /tmp/deathterminal-<uid> (mode 0700,
//! must be owned by the user).

const std = @import("std");
const builtin = @import("builtin");
const env_mod = @import("../platform/env.zig");
const posix = std.posix;
const pty = @import("../terminal/pty.zig");
const scripts = @import("shell_scripts");

pub const Shell = enum { bash, zsh, fish };

pub fn script(shell: Shell) []const u8 {
    return switch (shell) {
        .bash => scripts.bash,
        .zsh => scripts.zsh,
        .fish => scripts.fish,
    };
}

pub fn detect(program: []const u8) ?Shell {
    const base = std.fs.path.basename(program);
    const name = if (std.mem.startsWith(u8, base, "-")) base[1..] else base;
    return std.meta.stringToEnum(Shell, name);
}

/// The shell options with the integration wired in, given the directory
/// holding the written files. `user_zdotdir` is the inherited ZDOTDIR.
pub fn plan(arena: std.mem.Allocator, opts: pty.ShellOptions, program: []const u8, dir: []const u8, user_zdotdir: ?[]const u8) !pty.ShellOptions {
    const shell = detect(program) orelse return opts;
    var out = opts;
    var env = std.ArrayList([]const u8).init(arena);
    try env.appendSlice(opts.env);
    try env.append("DEATHTERMINAL_SHELL_INTEGRATION=1");
    switch (shell) {
        .bash => {
            if (opts.args.len != 0) return opts;
            const args = try arena.alloc([]const u8, 2);
            args[0] = "--rcfile";
            args[1] = try std.fs.path.join(arena, &.{ dir, "bashrc" });
            out.args = args;
        },
        .zsh => {
            for (opts.env) |kv| if (std.mem.startsWith(u8, kv, "ZDOTDIR=")) return opts;
            try env.append(try std.fmt.allocPrint(arena, "ZDOTDIR={s}/zsh", .{dir}));
            try env.append(try std.fmt.allocPrint(arena, "DT_SI_DIR={s}", .{dir}));
            if (user_zdotdir) |z| try env.append(try std.fmt.allocPrint(arena, "DT_USER_ZDOTDIR={s}", .{z}));
        },
        .fish => {
            const args = try arena.alloc([]const u8, opts.args.len + 2);
            args[0] = "--init-command";
            args[1] = try std.fmt.allocPrint(arena, "source '{s}/fish.fish'", .{dir});
            @memcpy(args[2..], opts.args);
            out.args = args;
        },
    }
    out.env = env.items;
    return out;
}

const bashrc =
    \\# Generated by Death Terminal (shell.integration = true): load the
    \\# user's ~/.bashrc, then the OSC 133 integration.
    \\if [ -f "$HOME/.bashrc" ]; then . "$HOME/.bashrc"; fi
    \\. "$DT_SI_DIR/bash.sh"
    \\
;

const zshenv =
    \\# Generated by Death Terminal (shell.integration = true): restore the
    \\# user's ZDOTDIR, load their .zshenv, then the OSC 133 integration
    \\# (its precmd/preexec hooks survive the rest of the startup files).
    \\if [[ -n "${DT_USER_ZDOTDIR-}" ]]; then ZDOTDIR=$DT_USER_ZDOTDIR; else unset ZDOTDIR; fi
    \\unset DT_USER_ZDOTDIR
    \\[[ -f "${ZDOTDIR:-$HOME}/.zshenv" ]] && source "${ZDOTDIR:-$HOME}/.zshenv"
    \\[[ -o interactive ]] && source "$DT_SI_DIR/zsh.zsh"
    \\
;

/// Write the integration files and return their directory, or null if no
/// private directory could be made.
pub fn writeFiles(buf: []u8) ?[]const u8 {
    const dir = runtimeDir(buf) orelse return null;
    var d = std.fs.openDirAbsolute(dir, .{}) catch return null;
    defer d.close();
    d.makePath("zsh") catch return null;
    const files = [_][2][]const u8{
        .{ "bash.sh", scripts.bash },
        .{ "zsh.zsh", scripts.zsh },
        .{ "fish.fish", scripts.fish },
        .{ "bashrc", bashrc },
        .{ "zsh/.zshenv", zshenv },
    };
    for (files) |f| d.writeFile(.{ .sub_path = f[0], .data = f[1], .flags = .{ .mode = if (builtin.os.tag == .windows) 0 else 0o600 } }) catch return null;
    return dir;
}

extern "c" fn getuid() u32;
const c_getuid = getuid;

fn runtimeDir(buf: []u8) ?[]const u8 {
    if (builtin.os.tag == .windows) return null;
    const uid = c_getuid();
    const path = if (env_mod.get("XDG_RUNTIME_DIR")) |x|
        std.fmt.bufPrint(buf, "{s}/deathterminal", .{x}) catch return null
    else
        std.fmt.bufPrint(buf, "/tmp/deathterminal-{d}", .{uid}) catch return null;
    posix.mkdir(path, 0o700) catch |err| switch (err) {
        error.PathAlreadyExists => {},
        else => return null,
    };
    // Refuse a directory someone else owns (or a symlink to one).
    const st = posix.fstatat(posix.AT.FDCWD, path, posix.AT.SYMLINK_NOFOLLOW) catch return null;
    if (st.uid != uid or (st.mode & posix.S.IFMT) != posix.S.IFDIR) return null;
    if (st.mode & 0o077 != 0) return null;
    return path;
}

/// `opts` with the integration added when `enabled` and the shell is
/// supported. On any failure the shell starts unchanged.
pub fn apply(arena: std.mem.Allocator, opts: pty.ShellOptions, enabled: bool) pty.ShellOptions {
    // bash/zsh/fish only; PowerShell and cmd get no integration (yet).
    if (builtin.os.tag == .windows) return opts;
    if (!enabled) return opts;
    const program: []const u8 = if (opts.program.len > 0) opts.program else env_mod.get("SHELL") orelse "/bin/sh";
    if (detect(program) == null) return opts;
    const buf = arena.alloc(u8, std.fs.max_path_bytes) catch return opts;
    const dir = writeFiles(buf) orelse return opts;
    var out = plan(arena, opts, program, dir, env_mod.get("ZDOTDIR")) catch return opts;
    // bash and zsh find the snippets through DT_SI_DIR.
    var env = std.ArrayList([]const u8).init(arena);
    env.appendSlice(out.env) catch return opts;
    for (out.env) |kv| if (std.mem.startsWith(u8, kv, "DT_SI_DIR=")) return out;
    env.append(std.fmt.allocPrint(arena, "DT_SI_DIR={s}", .{dir}) catch return opts) catch return opts;
    out.env = env.items;
    return out;
}

test "detect" {
    try std.testing.expectEqual(Shell.bash, detect("/bin/bash").?);
    try std.testing.expectEqual(Shell.zsh, detect("-zsh").?);
    try std.testing.expectEqual(Shell.fish, detect("/usr/local/bin/fish").?);
    try std.testing.expect(detect("/bin/dash") == null);
}

test "plan per shell" {
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const b = try plan(arena, .{}, "/bin/bash", "/run/x", null);
    try std.testing.expectEqualStrings("--rcfile", b.args[0]);
    try std.testing.expectEqualStrings("/run/x/bashrc", b.args[1]);
    // Custom bash args (e.g. a login shell) are left alone.
    const bl = try plan(arena, .{ .args = &.{"-l"} }, "bash", "/run/x", null);
    try std.testing.expectEqual(@as(usize, 1), bl.args.len);
    try std.testing.expectEqual(@as(usize, 0), bl.env.len);

    const z = try plan(arena, .{}, "/usr/bin/zsh", "/run/x", "/home/u/.zsh");
    try std.testing.expectEqualStrings("ZDOTDIR=/run/x/zsh", z.env[1]);
    try std.testing.expectEqualStrings("DT_USER_ZDOTDIR=/home/u/.zsh", z.env[3]);

    const f = try plan(arena, .{ .args = &.{"-l"} }, "fish", "/run/x", null);
    try std.testing.expectEqualStrings("--init-command", f.args[0]);
    try std.testing.expectEqualStrings("source '/run/x/fish.fish'", f.args[1]);
    try std.testing.expectEqualStrings("-l", f.args[2]);

    const d = try plan(arena, .{}, "/bin/dash", "/run/x", null);
    try std.testing.expectEqual(@as(usize, 0), d.args.len);
}

test "the snippets emit every mark" {
    for ([_][]const u8{ scripts.bash, scripts.zsh, scripts.fish }) |s| {
        for ([_][]const u8{ "133;A", "133;B", "133;C", "133;D", "]7;" }) |m|
            try std.testing.expect(std.mem.indexOf(u8, s, m) != null);
    }
}
