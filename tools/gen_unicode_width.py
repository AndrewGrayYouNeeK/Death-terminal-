#!/usr/bin/env python3
"""Generate src/terminal/unicode_width.zig from Python's unicodedata.

Run: python3 tools/gen_unicode_width.py > src/terminal/unicode_width.zig

Width rules (wcwidth-style):
  0: combining marks (Mn, Me), format chars (Cf) except U+00AD,
     Hangul Jamo medial vowels/final consonants (U+1160..U+11FF), U+200B
  2: East Asian Wide (W) or Fullwidth (F), which includes emoji with
     default emoji presentation
  1: everything else
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_zero(cp):
    if cp == 0x00AD:
        return False
    if 0x1160 <= cp <= 0x11FF or cp == 0x200B:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_wide(cp):
    if is_zero(cp):
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def emit(name, rs, last=False):
    print(f"pub const {name} = [_]Range{{")
    for a, b in rs:
        print(f"    .{{ .lo = 0x{a:04X}, .hi = 0x{b:04X} }},")
    print("};" if last else "};\n")


print(f"// Generated by tools/gen_unicode_width.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
print("pub const Range = struct { lo: u21, hi: u21 };\n")
emit("zero_width", ranges(is_zero))
emit("wide", ranges(is_wide), last=True)
